#!/usr/bin/env python3
"""Compile the final Preview metadata-only gate from retained local contracts.

No cloud calls or apply builders are invoked. The resulting SQL is bundled in
the last existing schema job; CI checks reproducibility and executes it on PG16.
"""
import hashlib
import importlib.util
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
DESTINATION = ROOT / 'scripts/deployment/preview-schema-verification.sql'


def module(name, filename, checksum):
    path = ROOT / 'scripts' / filename
    if hashlib.sha256(path.read_bytes()).hexdigest() != checksum:
        raise SystemExit('STOP: RETAINED_SCHEMA_CONTRACT_CHANGED')
    spec = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


def build():
    grants = module('schema_grants', 'grant-preview-v2-runtime.py',
        'b086e77e8f64011364261b61cbda93a0828c5f76ad53874f798722120fabc10c')
    acl = module('schema_acl', 'read-preview-v2-schema-acl.py',
        '13f93b5ffdc8a4f3cdec501bd965e2673be4f4418fe656484242c969e3cb2bb2')
    verifier = module('schema_identity', 'verify-preview-v2-runtime.py',
        'a89c33be26755c0e948e5e80c140752b978d13a039d82a9bae95f03e5692b940')
    routines = {}
    triggers = []
    for prefix in ('025', '027', '029', '030', '031', '032'):
        files = [p for p in (ROOT / 'backend/migrations/versions').glob(prefix + '_*.sql')
                 if not p.stem.endswith('_rollback')]
        if len(files) != 1:
            raise SystemExit('STOP: CANONICAL_ROUTINE_SOURCE_AMBIGUOUS')
        source = files[0].read_text()
        for name, timing, events, table, function in re.findall(
                r'CREATE TRIGGER ([a-z_]+)\s+(BEFORE|AFTER) ((?:INSERT|UPDATE|DELETE)(?: OR (?:INSERT|UPDATE|DELETE))*) ON ([a-z_.]+)\s+FOR EACH ROW EXECUTE FUNCTION ([a-z_.]+)\(\);', source):
            table = table if '.' in table else 'public.' + table
            function = function if '.' in function else 'public.' + function
            kind = 1 + (2 if timing == 'BEFORE' else 0) + sum({'INSERT':4, 'DELETE':8, 'UPDATE':16}[e] for e in events.split(' OR '))
            triggers.append(f"('{name}','{table}','{function}()',{kind})")
        for name, arguments, header, body in re.findall(
                r'CREATE (?:OR REPLACE )?FUNCTION ([a-z_.]+)\(([^)]*)\)(.*?)AS \$\$(.*?)\$\$',
                source, re.S):
            name = name if '.' in name else 'public.' + name
            signature = name + ('(text,boolean)' if arguments else '()')
            resolver = name == 'khedmah_taxi.resolve_actor_locked'
            if bool(arguments) != resolver or ('SECURITY DEFINER' in header) != resolver:
                raise SystemExit('STOP: CANONICAL_ROUTINE_SHAPE_CHANGED')
            routines[signature] = (body, resolver)
    if len(routines) != 9 or len(triggers) != 12:
        raise SystemExit('STOP: CANONICAL_ROUTINE_COUNT_CHANGED')
    routine_checks = []
    for index, (signature, (body, resolver)) in enumerate(sorted(routines.items())):
        delimiter = '$canonical' + str(index) + '$'
        if delimiter in body:
            raise SystemExit('STOP: ROUTINE_DELIMITER_COLLISION')
        config = "p.proconfig=ARRAY['search_path=pg_catalog, pg_temp']::text[]" if resolver else 'p.proconfig IS NULL'
        arguments = """AND p.proargnames=ARRAY['session_hash','wants_driver','user_id','vehicle_id','zone_code','driver_revision','vehicle_revision','valid_until']::text[]
     AND p.proallargtypes=ARRAY[25,16,25,25,25,25,25,1184]::oid[]
     AND p.proargmodes=ARRAY['i','i','t','t','t','t','t','t']::"char"[]""" if resolver else ''
        routine_checks.append(f"""
 IF NOT EXISTS (SELECT 1 FROM pg_proc p JOIN pg_language l ON l.oid=p.prolang
   WHERE p.oid=to_regprocedure('{signature}') AND p.prokind='f'
     AND l.lanname='plpgsql' AND p.provolatile='v' AND p.proparallel='u'
     AND NOT p.proisstrict AND NOT p.proleakproof AND p.pronargdefaults=0 AND p.provariadic=0
     AND pg_get_userbyid(p.proowner)='khedmah_migrator'
     AND p.prosecdef={'true' if resolver else 'false'} AND {config}
     AND p.proretset={'true' if resolver else 'false'}
     AND p.prorettype='pg_catalog.{'record' if resolver else 'trigger'}'::regtype
     {arguments}
     AND p.prosrc={delimiter}{body}{delimiter}) THEN
   RAISE EXCEPTION 'PREVIEW_SCHEMA_ROUTINE_BODY_OR_SECURITY_DRIFT';
 END IF;
""")
    tables = sorted(['public.' + n for n in (*grants.PUBLIC_TABLES, 'category_taxonomy_022_before_image')]
                    + ['khedmah_taxi.' + n for n in grants.TAXI_TABLES])
    names = ','.join("'" + n + "'" for n in tables)
    return ("-- Generated by build-preview-schema-verification.py; metadata only, no apply path.\n"
        "BEGIN ISOLATION LEVEL REPEATABLE READ, READ ONLY;\nSET LOCAL search_path=pg_catalog;\n"
        "DO $verification$ DECLARE observed jsonb; expected jsonb; BEGIN\n"
        + verifier.identity_guard('khedmah_migrator') + grants.acl_assertion(acl)
        + f"""
 IF (SELECT array_agg(n.nspname||'.'||c.relname ORDER BY (n.nspname||'.'||c.relname) COLLATE "C")
     FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
     WHERE n.nspname !~ '^pg_' AND n.nspname<>'information_schema' AND c.relkind IN ('r','p','v','m','f','S'))
       IS DISTINCT FROM ARRAY[{names}]::text[]
    OR EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
       WHERE n.nspname IN ('public','khedmah_taxi') AND c.relkind IN ('r','p','v','m','f','S')
         AND (c.relkind<>'r' OR pg_get_userbyid(c.relowner)<>'khedmah_migrator')) THEN
   RAISE EXCEPTION 'PREVIEW_SCHEMA_TABLE_SET_OR_OWNER_DRIFT';
 END IF;
 IF (SELECT count(*) FROM pg_roles WHERE rolname IN
       ('khedmah_app','khedmah_migrator','khedmah_runtime_role','khedmah_migration_role')
       AND NOT rolsuper AND NOT rolcreatedb AND NOT rolcreaterole AND NOT rolreplication AND NOT rolbypassrls
       AND rolcanlogin=(rolname IN ('khedmah_app','khedmah_migrator')))<>4 THEN
   RAISE EXCEPTION 'PREVIEW_SCHEMA_ROLE_ATTRIBUTE_DRIFT';
 END IF;
 IF EXISTS (SELECT 1 FROM (VALUES {','.join(triggers)}) e(name,relation,routine,kind)
   WHERE NOT EXISTS (SELECT 1 FROM pg_trigger t WHERE NOT t.tgisinternal
     AND t.tgname=e.name AND t.tgrelid=to_regclass(e.relation) AND t.tgfoid=to_regprocedure(e.routine)
     AND t.tgtype=e.kind AND t.tgenabled='O' AND t.tgconstraint=0 AND t.tgnargs=0
     AND t.tgqual IS NULL AND t.tgattr=''::int2vector)) THEN
   RAISE EXCEPTION 'PREVIEW_SCHEMA_TRIGGER_DRIFT';
 END IF;
""" + ''.join(routine_checks) + "END $verification$;\nROLLBACK;\n"
        "SELECT 'PREVIEW_V2_SCHEMA_AND_RUNTIME_ACL_READONLY_VERIFIED';\n")


if __name__ == '__main__':
    result = build()
    if sys.argv[1:] == ['--check']:
        if DESTINATION.read_text() != result:
            raise SystemExit('STOP: GENERATED_SCHEMA_VERIFICATION_DRIFT')
    elif not sys.argv[1:]:
        DESTINATION.write_text(result)
    else:
        raise SystemExit('usage: build-preview-schema-verification.py [--check]')
